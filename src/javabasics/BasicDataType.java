package javabasics;

public class BasicDataType {
    public static void main(String[] args) {
        int a = 5;
        float b = 2.1F;
        double c = 3.2;
        char d = 'A';
        boolean e = false;

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);
    }

}
